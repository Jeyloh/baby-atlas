import { prisma } from "@baby-atlas/db";
import { MAX_JOURNAL_PHOTOS } from "@baby-atlas/schemas";
import { canEditJournalEntry, journalPhotoKey, journalThumbKey } from "@baby-atlas/utils";
import { auth } from "@/lib/auth";
import { getChildMembership } from "@/lib/journal/access";
import { detectImageType, isAllowedDeclaredType } from "@/lib/journal/image-type";
import { ImageProcessingError, processJournalImage } from "@/lib/journal/process-image";
import { getStorage } from "@/lib/storage";

export const runtime = "nodejs";
export const maxDuration = 30;

// The client downsizes to about 1 MB. Vercel functions accept at most 4.5 MB per request anyway.
const MAX_UPLOAD_BYTES = 8 * 1024 * 1024;
const MULTIPART_OVERHEAD_BYTES = 64 * 1024;

function fail(status: number, error: string) {
  return Response.json({ error }, { status });
}

/**
 * POST multipart: `entryId` and one `file`. The client sends one photo per
 * request so it can show progress per photo.
 */
export async function POST(request: Request) {
  const session = await auth();
  const userId = session?.user?.id;
  if (!userId) return fail(401, "unauthorized");

  const declaredLength = Number(request.headers.get("content-length"));
  if (declaredLength > MAX_UPLOAD_BYTES + MULTIPART_OVERHEAD_BYTES) return fail(413, "too_large");

  let form: FormData;
  try {
    form = await request.formData();
  } catch {
    return fail(400, "invalid_request");
  }
  const entryId = form.get("entryId");
  const file = form.get("file");
  if (typeof entryId !== "string" || !entryId || !(file instanceof File)) {
    return fail(400, "invalid_request");
  }

  const entry = await prisma.journalEntry.findUnique({
    where: { id: entryId },
    select: { id: true, childId: true, authorId: true },
  });
  const membership = entry ? await getChildMembership(userId, entry.childId) : null;
  if (!entry || !membership) return fail(404, "not_found");
  if (!canEditJournalEntry(membership.role, entry.authorId, userId)) return fail(403, "forbidden");

  if (file.size === 0) return fail(400, "invalid_request");
  if (file.size > MAX_UPLOAD_BYTES) return fail(413, "too_large");
  if (!isAllowedDeclaredType(file.type)) return fail(415, "unsupported_type");

  const existing = await prisma.journalPhoto.count({ where: { entryId: entry.id } });
  if (existing >= MAX_JOURNAL_PHOTOS) return fail(409, "too_many_photos");

  const bytes = new Uint8Array(await file.arrayBuffer());
  const detected = detectImageType(bytes);
  if (!detected) return fail(415, "unsupported_type");

  let image;
  try {
    image = await processJournalImage(bytes);
  } catch (error) {
    if (!(error instanceof ImageProcessingError)) throw error;
    // sharp's prebuilt libvips reads AVIF but not HEVC, so most HEIC files end up here
    return fail(415, detected === "image/heic" ? "heic_unsupported" : "unreadable_image");
  }

  const last = await prisma.journalPhoto.aggregate({
    where: { entryId: entry.id },
    _max: { position: true },
  });

  // The key needs the photo id, and the id is generated by the database
  const photo = await prisma.journalPhoto.create({
    data: {
      entryId: entry.id,
      storageKey: "",
      mimeType: image.mimeType,
      width: image.width,
      height: image.height,
      sizeBytes: image.full.length,
      position: (last._max.position ?? -1) + 1,
    },
    select: { id: true },
  });

  // Two uploads racing past the check above could both fit, so check again
  const total = await prisma.journalPhoto.count({ where: { entryId: entry.id } });
  if (total > MAX_JOURNAL_PHOTOS) {
    await prisma.journalPhoto.delete({ where: { id: photo.id } });
    return fail(409, "too_many_photos");
  }

  const storage = getStorage();
  const key = journalPhotoKey(entry.childId, entry.id, photo.id);
  try {
    await storage.put(key, image.full, image.mimeType);
    await storage.put(journalThumbKey(key), image.thumb, image.mimeType);
    await prisma.journalPhoto.update({ where: { id: photo.id }, data: { storageKey: key } });
  } catch (error) {
    console.error("[journal] photo upload failed", error);
    await prisma.journalPhoto.delete({ where: { id: photo.id } }).catch(() => undefined);
    await Promise.allSettled([storage.delete(key), storage.delete(journalThumbKey(key))]);
    return fail(500, "storage_failed");
  }

  return Response.json(
    { id: photo.id, width: image.width, height: image.height, sizeBytes: image.full.length },
    { status: 201 }
  );
}
